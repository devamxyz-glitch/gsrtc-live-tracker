export const TABLES = { en, gu };
let lang = 'en';

export function setLang(l) {
  lang = TABLES[l] ? l : 'en';
  document.documentElement.lang = lang;
  return lang;
}
export function getLang() { return lang; }

/**
 * The occupancy scale, lowest to highest, as translation keys.
 *
 * Lives here because more than one screen names these levels now — the reporting control in
 * Track and the departure list in Routes — and two copies of an ordered scale drift the moment
 * a level is added in the middle.
 */
export const OCCUPANCY_KEYS = ['occEmpty', 'occSeats', 'occStanding', 'occCrowded', 'occFull'];

/** A stored level (1-5) as a short phrase, or '' for a level nobody has reported. */
export function occupancyLabel(level) {
  const key = OCCUPANCY_KEYS[Number(level) - 1];
  return key ? t(key) : '';
}

/** t('minsAgo', {n: 3}) */
export function t(key, vars) {
  let s = (TABLES[lang] && TABLES[lang][key]) ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** Picks the Gujarati field when the UI is in Gujarati and the value is non-empty. */
export function localName(english, gujarati) {
  const g = (gujarati || '').trim();
  return lang === 'gu' && g ? g : (english || g || '');
}

export function detectLang() {
  const saved = localStorage.getItem('st.lang');
  if (saved && TABLES[saved]) return saved;
  return (navigator.languages || [navigator.language || 'en']).some((l) => /^gu/i.test(l)) ? 'gu' : 'en';
}
